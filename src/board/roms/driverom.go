package roms

func PatchDriveRom(rom *[]byte) {
	(*rom)[0x2ae4] = 0xea // Don't check ROM checksum
	(*rom)[0x2ae5] = 0xea
	(*rom)[0x2ae8] = 0xea
	(*rom)[0x2ae9] = 0xea
	(*rom)[0x2c9b] = 0xf2 // DOS idle loop
	(*rom)[0x2c9c] = 0x00
	(*rom)[0x3594] = 0x20 // Write sector
	(*rom)[0x3595] = 0xf2
	(*rom)[0x3596] = 0xf5
	(*rom)[0x3597] = 0xf2
	(*rom)[0x3598] = 0x01
	(*rom)[0x3b0c] = 0xf2 // Format track
	(*rom)[0x3b0d] = 0x02
}
