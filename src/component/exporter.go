package component

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io"
	"log"
	"os"
	"path/filepath"
	"strings"
	"text/template"
	"unicode"
)

const (
	// ExporterPrefix is a constant used to identify export-related comments in the code during parsing and generation.
	exporterPrefix     = "//symphony:export"
	exporterFileSuffix = "_reflect_gen"
)

// reflectTemplate is a predefined Go template used to generate type-specific reflection code for a given struct.
const reflectTemplate = `// Code generated by symphony-generator. DO NOT EDIT.
package {{.PackageName}}

type {{.StructName}}Reflect struct {
    ref *{{.StructName}}
}

func New{{.StructName}}Reflect(r *{{.StructName}}) *{{.StructName}}Reflect {
    reflector := &{{.StructName}}Reflect{ref: r}
    {{range .ExportedFuncs}}
    r.AddProperty("{{.ID}}", "{{.PropertyName}}", false, reflector.{{.GetterName}}, reflector.{{.SetterName}}){{end}}
    return reflector
}
`

// ExportedFunc represents a mapping between a property and its associated getter and setter functions.
type ExportedFunc struct {
	ID           string
	PropertyName string
	GetterName   string
	SetterName   string
}

// FuncInfo represents metadata about a function, including its name and associated property name.
type FuncInfo struct {
	Name         string
	PropertyName string
}

// TemplateData contains metadata required for generating reflective code for a specific struct.
type TemplateData struct {
	PackageName   string
	StructName    string
	ExportedFuncs []ExportedFunc
}

// StructData represents metadata about a struct, including its getters, setters, and exported functions.
type StructData struct {
	StructName    string
	TempGetters   map[string]FuncInfo
	TempSetters   map[string]FuncInfo
	ExportedFuncs []ExportedFunc
}

// Generator represents a structure for parsing source code and generating files based on specific struct data and methods.
type Generator struct {
	fileSet     *token.FileSet
	inputFile   string
	packageName string
	structs     map[string]*StructData
	output      io.Writer
	useFile     bool
}

// NewGenerator initializes and returns a new Generator instance for the specified input file.
func NewGenerator(inputFile string, useFile bool) *Generator {
	return &Generator{
		fileSet:   token.NewFileSet(),
		inputFile: inputFile,
		useFile:   useFile,
		output:    os.Stdout,
		structs:   make(map[string]*StructData),
	}
}

func (g *Generator) SetOutput(w io.Writer) {
	g.output = w
}

// ParseAndGenerate parses the input file, extracts annotated functions, and generates reflection-based code for structs.
func (g *Generator) ParseAndGenerate() error {
	node, err := parser.ParseFile(g.fileSet, g.inputFile, nil, parser.ParseComments)
	if err != nil {
		return fmt.Errorf("error parsing file %s: %w", g.inputFile, err)
	}

	g.packageName = node.Name.Name

	ast.Inspect(node, func(n ast.Node) bool {
		funcDecl, ok := n.(*ast.FuncDecl)
		if !ok || funcDecl.Doc == nil || funcDecl.Recv == nil || len(funcDecl.Recv.List) == 0 {
			return true
		}

		// Get the receiver struct name
		var structName string
		if starExpr, ok := funcDecl.Recv.List[0].Type.(*ast.StarExpr); ok {
			if ident, ok := starExpr.X.(*ast.Ident); ok {
				structName = ident.Name
			}
		}

		if structName == "" {
			return true // Not a method on a struct we can identify
		}

		// Ensure a StructData entry exists for this struct
		if _, ok = g.structs[structName]; !ok {
			g.structs[structName] = &StructData{
				StructName:  structName,
				TempGetters: make(map[string]FuncInfo),
				TempSetters: make(map[string]FuncInfo),
			}
		}
		structData := g.structs[structName]

		for _, comment := range funcDecl.Doc.List {
			if strings.HasPrefix(comment.Text, exporterPrefix) {
				propertyName := strings.TrimSpace(strings.TrimPrefix(comment.Text, exporterPrefix))
				funcName := funcDecl.Name.Name
				if strings.HasPrefix(funcName, "get") {
					id := g.deriveID(funcName, "get")
					structData.TempGetters[id] = FuncInfo{Name: funcName, PropertyName: propertyName}
				} else if strings.HasPrefix(funcName, "set") {
					id := g.deriveID(funcName, "set")
					structData.TempSetters[id] = FuncInfo{Name: funcName, PropertyName: propertyName}
				}
			}
		}
		return true
	})

	// Loop through each found struct to match functions and generate files
	for _, data := range g.structs {
		g.matchFunctions(data)
		if err = g.generateFile(data); err != nil {
			// Continue generating for other structs but collect errors
			log.Printf("error generating file for struct %s: %v", data.StructName, err)
		}
	}

	return nil
}

// deriveID generates an identifier by removing the specified prefix from the function name and converting the first letter of the remaining name to lowercase.
func (g *Generator) deriveID(funcName, prefix string) string {
	baseName := strings.TrimPrefix(funcName, prefix)
	if baseName == "" {
		return ""
	}
	runes := []rune(baseName)
	runes[0] = unicode.ToLower(runes[0])
	return string(runes)
}

// matchFunctions processes a given StructData instance and pairs getter and setter functions by their derived IDs.
// It then populates the ExportedFuncs slice in the StructData with matched getter-setter pairs.
// Logs a warning if a getter function does not have a corresponding setter.
func (g *Generator) matchFunctions(data *StructData) {
	data.ExportedFuncs = []ExportedFunc{}
	for id, getterInfo := range data.TempGetters {
		setterInfo, ok := data.TempSetters[id]
		if !ok {
			log.Printf("warning: Getter '%s' has no corresponding Setter for ID '%s'", getterInfo.Name, id)
			continue
		}
		data.ExportedFuncs = append(data.ExportedFuncs, ExportedFunc{
			ID:           id,
			PropertyName: getterInfo.PropertyName,
			GetterName:   getterInfo.Name,
			SetterName:   setterInfo.Name,
		})
	}
}

// generateFile generates a Go file containing reflection code for the provided struct data.
// It uses a predefined template to create methods for exporting getter and setter functions.
// Returns an error if template parsing, file creation, or file execution fails.
func (g *Generator) generateFile(data *StructData) error {
	if len(data.ExportedFuncs) == 0 {
		return nil
	}
	tmpl, err := template.New("reflect").Parse(reflectTemplate)
	if err != nil {
		return fmt.Errorf("error while creating template: %w", err)
	}
	writer := g.output
	if g.useFile {
		baseName := strings.ToLower(data.StructName)
		outputFilename := fmt.Sprintf("%s%s.go", baseName, exporterFileSuffix)
		outputFilepath := filepath.Join(filepath.Dir(g.inputFile), outputFilename)
		if f, fErr := os.Create(outputFilepath); fErr != nil {
			return fmt.Errorf("error while creating output file: %w", fErr)
		} else {
			writer = f
			defer f.Close()
		}
	}
	templateData := TemplateData{
		PackageName:   g.packageName,
		StructName:    data.StructName,
		ExportedFuncs: data.ExportedFuncs,
	}
	return tmpl.Execute(writer, &templateData)
}

func (g *Generator) Write(p []byte) (n int, err error) {
	fmt.Println(string(p))
	return len(p), nil
}
