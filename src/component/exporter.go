// exporterPrefix defines the prefix used for exporting data in symphony.
// exporterFileSuffix specifies the suffix for generated reflection files.
// readonlyKeyword represents the 'readonly' keyword used in specific contexts.
const (
	exporterPrefix     = "symphony:export"
	exporterFileSuffix = "_reflect_gen"
	readonlyKeyword    = "readonly"
)

// reflectTemplate is a Go template string used to generate reflection-based code for struct properties and methods.
const reflectTemplate = `package {{.PackageName}}
// Code generated by symphony-generator. DO NOT EDIT.

const (
	{{- range .Properties}}
	{{.IDVarName}} = "{{.FieldName}}"
	{{- end}}
)

type {{.StructName}}Reflect struct {
	ref *{{.StructName}}
}

func New{{.StructName}}Reflect(r *{{.StructName}}) *{{.StructName}}Reflect {
	reflector := &{{.StructName}}Reflect{ref: r}
	{{- range .Properties}}
	r.AddProperty({{.IDVarName}}, "{{.Documentation}}", {{.ReadOnly}}, reflector.{{.GetterName}}, reflector.{{.SetterName}})
	{{- end}}
	return reflector
}
{{range .Properties}}
// {{.GetterName}} is the generated getter for the {{.FieldName}} field.
func (s *{{$.StructName}}Reflect) {{.GetterName}}() {{.FieldType}} {
	return s.ref.{{.FieldName}}
}

// {{.SetterName}} is the generated setter for the {{.FieldName}} field.{{if not .ReadOnly}}
func (s *{{$.StructName}}Reflect) {{.SetterName}}(v {{.FieldType}}) error {
	s.ref.{{.FieldName}} = v
	return nil
}{{else}}
func (s *{{$.StructName}}Reflect) {{.SetterName}}(v {{.FieldType}}) error {
	// property {{.FieldName}} is read-only.
	return nil
}
{{end}}
{{end}}
`

// Property represents a single field definition in a structure with metadata for reflection and code generation.
type Property struct {
	FieldName     string
	IDVarName     string
	GetterName    string
	SetterName    string
	FieldType     string
	Documentation string
	ReadOnly      bool
}

// TemplateData is a structure that holds metadata for generating reflective templates for a given Go struct.
// It contains the package name, struct name, and a slice of properties defined for the struct.
type TemplateData struct {
	PackageName string
	StructName  string
	Properties  []Property
}

// StructData represents metadata for a Go struct, including its name and a list of associated property definitions.
type StructData struct {
	StructName string
	Properties []Property
}

// Generator is a type for parsing Go source files and generating reflective code for its structs.
type Generator struct {
	fileSet     *token.FileSet
	inputFile   string
	packageName string
	structs     map[string]*StructData
	output      io.Writer
	useFile     bool
}

// NewGenerator initializes and returns a new Generator instance configured with the provided input file and options.
func NewGenerator(inputFile string, useFile bool) *Generator {
	return &Generator{
		fileSet:   token.NewFileSet(),
		inputFile: inputFile,
		useFile:   useFile,
		output:    os.Stdout,
		structs:   make(map[string]*StructData),
	}
}

// SetOutput sets the output writer where the generated code or data will be written.
func (g *Generator) SetOutput(w io.Writer) {
	g.output = w
}

// isTypeAllowed determines if a given field type is allowed based on predefined allowed base and slice element types.
func isTypeAllowed(fieldType string) bool {
	if allowedBaseTypes[fieldType] {
		return true
	}
	if strings.HasPrefix(fieldType, "[]") {
		sliceElementType := strings.TrimPrefix(fieldType, "[]")
		if allowedSliceElementTypes[sliceElementType] {
			return true
		}
	}
	return false
}

// ParseAndGenerate processes the input Go source file, extracts annotated struct information, and generates output files.
// It uses the specified file set and input file, analyzes struct types, and generates code for those matching criteria.
// Returns an error if parsing or file generation fails.
func (g *Generator) ParseAndGenerate() error {
	node, err := parser.ParseFile(g.fileSet, g.inputFile, nil, parser.ParseComments)
	if err != nil {
		return fmt.Errorf("error parsing file %s: %w", g.inputFile, err)
	}

	g.packageName = node.Name.Name

	ast.Inspect(node, func(n ast.Node) bool {
		typeSpec, ok := n.(*ast.TypeSpec)
		if !ok {
			return true
		}
		structType, ok := typeSpec.Type.(*ast.StructType)
		if !ok {
			return true
		}

		structName := typeSpec.Name.Name
		if _, ok := g.structs[structName]; !ok {
			g.structs[structName] = &StructData{
				StructName: structName,
				Properties: []Property{},
			}
		}
		structData := g.structs[structName]

		for _, field := range structType.Fields.List {
			if field.Comment == nil || len(field.Names) == 0 {
				continue
			}
			commentText := field.Comment.List[0].Text
			if !strings.Contains(commentText, exporterPrefix) {
				continue
			}
			fieldName := field.Names[0].Name
			var typeNameBuf bytes.Buffer
			if err := printer.Fprint(&typeNameBuf, g.fileSet, field.Type); err != nil {
				log.Printf("error getting type for field %s: %v", fieldName, err)
				continue
			}
			fieldType := typeNameBuf.String()
			if !isTypeAllowed(fieldType) {
				log.Printf("warning: Skipping field '%s' with unsupported type '%s'", fieldName, fieldType)
				continue
			}

			goName := strings.ToUpper(fieldName[:1]) + fieldName[1:]
			doc := strings.TrimSpace(strings.Replace(commentText, exporterPrefix, "", -1))
			doc = strings.TrimPrefix(doc, "//")
			isReadOnly := strings.Contains(doc, readonlyKeyword)
			doc = strings.TrimSpace(strings.Replace(doc, readonlyKeyword, "", -1))
			if doc == "" {
				doc = goName
			}

			structData.Properties = append(structData.Properties, Property{
				FieldName:     fieldName,
				IDVarName:     fieldName + "Id",
				GetterName:    "get" + goName,
				SetterName:    "set" + goName,
				FieldType:     fieldType,
				Documentation: doc,
				ReadOnly:      isReadOnly,
			})
		}
		return true
	})

	for _, data := range g.structs {
		if err := g.generateFile(data); err != nil {
			log.Printf("error generating file for struct %s: %v", data.StructName, err)
		}
	}

	return nil
}

// generateFile generates a Go source file for a given struct by applying template logic to the struct's properties.
// It writes output to the Generator's configured writer or to a file if file output is enabled.
// Returns an error if the template creation, execution, or file operations fail.
func (g *Generator) generateFile(data *StructData) error {
	if len(data.Properties) == 0 {
		return nil
	}
	tmpl, err := template.New("reflect").Parse(reflectTemplate)
	if err != nil {
		return fmt.Errorf("error while creating template: %w", err)
	}

	writer := g.output
	if g.useFile {
		baseName := strings.ToLower(data.StructName)
		outputFilename := fmt.Sprintf("%s%s.go", baseName, exporterFileSuffix)
		outputFilepath := filepath.Join(filepath.Dir(g.inputFile), outputFilename)
		f, fErr := os.Create(outputFilepath)
		if fErr != nil {
			return fmt.Errorf("error while creating output file: %w", fErr)
		}
		defer f.Close()
		writer = f
	}

	templateData := TemplateData{
		PackageName: g.packageName,
		StructName:  data.StructName,
		Properties:  data.Properties,
	}
	return tmpl.Execute(writer, &templateData)
}

