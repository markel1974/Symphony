// deriveID generates an identifier by removing the specified prefix from the function name and converting the first letter of the remaining name to lowercase.
func (g *Generator) deriveID(funcName, prefix string) string {
	baseName := strings.TrimPrefix(funcName, prefix)
	if baseName == "" {
		return ""
	}
	runes := []rune(baseName)
	runes[0] = unicode.ToLower(runes[0])
	return string(runes)
}

