package component

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"io"
	"log"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

// allowedBaseTypes defines a set of primitive types allowed for validation, represented as a map of type strings to bool.
var allowedBaseTypes = map[string]bool{
	"string": true, "bool": true, "int": true, "int8": true, "int16": true, "int32": true, "int64": true,
	"uint": true, "uint8": true, "uint16": true, "uint32": true, "uint64": true, "float32": true, "float64": true,
}

// allowedSliceElementTypes defines a set of allowed data types for elements in a slice, represented as a map for quick lookup.
var allowedSliceElementTypes = map[string]bool{
	"int": true, "int8": true, "int16": true, "int32": true, "int64": true,
	"uint": true, "uint8": true, "uint16": true, "uint32": true, "uint64": true,
}

// exporterPrefix defines the prefix used in exporter-related operations.
// exporterFileSuffix specifies the suffix for generated reflection files.
// readonlyKeyword represents the keyword for a readonly property.
const (
	exporterPrefix     = "symphony:export"
	exporterFileSuffix = "_reflect_gen"
	readonlyKeyword    = "readonly"
)

// reflectTemplate is a template string used for generating Go code that defines reflect-based accessors for struct properties.
const reflectTemplate = `package {{.PackageName}}

// Code generated by symphony-generator. DO NOT EDIT.

const (
	{{- range .Properties}}
	{{.IDVarName}} = "{{.FieldName}}"
	{{- end}}
)

type {{.StructName}}Reflect struct {
	ref *{{.StructName}}
}

func New{{.StructName}}Reflect(r *{{.StructName}}) *{{.StructName}}Reflect {
	reflector := &{{.StructName}}Reflect{ref: r}
	{{- range .Properties}}
	r.AddProperty({{.IDVarName}}, "{{.Documentation}}", {{.ReadOnly}}, reflector.{{.GetterName}}, reflector.{{.SetterName}})
	{{- end}}
	return reflector
}
{{range .Properties}}
// {{.GetterName}} is the generated getter for the  {{.FieldName}}.
func (s *{{$.StructName}}Reflect) {{.GetterName}}() {{.FieldType}} {
	{{.GetterBody}}
}

// {{.SetterName}} is the generated setter for the {{.FieldName}} field.{{if not .ReadOnly}}
func (s *{{$.StructName}}Reflect) {{.SetterName}}(v {{.FieldType}}) error {
	{{.SetterBody}}
}{{else}}
func (s *{{$.StructName}}Reflect) {{.SetterName}}(v {{.FieldType}}) error {
	// property {{.FieldName}} is read-only.
	return nil
}
{{end}}
{{end}}
`

// Property represents a struct field with additional metadata for getter, setter, and documentation purposes.
type Property struct {
	FieldName     string
	IDVarName     string
	GetterName    string
	SetterName    string
	FieldType     string
	Documentation string
	ReadOnly      bool
	GetterBody    string
	SetterBody    string
}

// TemplateData represents the structured data required to populate a template for code generation.
type TemplateData struct {
	PackageName string
	StructName  string
	Properties  []Property
}

// StructData represents a data structure containing metadata about a struct, including its name and associated properties.
type StructData struct {
	StructName string
	Properties []Property
}

// Generator is responsible for parsing Go source files and generating corresponding templates based on struct data.
type Generator struct {
	fileSet     *token.FileSet
	inputFile   string
	packageName string
	structs     map[string]*StructData
	output      io.Writer
	useFile     bool
}

// NewGenerator creates and initializes a new Generator with the specified input file and file usage flag.
func NewGenerator(inputFile string, useFile bool) *Generator {
	return &Generator{
		fileSet:   token.NewFileSet(),
		inputFile: inputFile,
		useFile:   useFile,
		output:    os.Stdout,
		structs:   make(map[string]*StructData),
	}
}

// SetOutput sets the output writer for the generator, directing where the generated code will be written.
func (g *Generator) SetOutput(w io.Writer) {
	g.output = w
}

// isTypeAllowed checks if a given field type is allowed based on predefined base and slice element type rules.
func isTypeAllowed(fieldType string) bool {
	if allowedBaseTypes[fieldType] {
		return true
	}
	if strings.HasPrefix(fieldType, "[]") {
		return allowedSliceElementTypes[strings.TrimPrefix(fieldType, "[]")]
	}
	return false
}

// ParseAndGenerate parses the input file for struct definitions and generates corresponding output with reflection metadata.
func (g *Generator) ParseAndGenerate() error {
	node, err := parser.ParseFile(g.fileSet, g.inputFile, nil, parser.ParseComments)
	if err != nil {
		return fmt.Errorf("error parsing file %s: %w", g.inputFile, err)
	}

	g.packageName = node.Name.Name

	typeMethods := make(map[string]map[string]*ast.FuncDecl)
	ast.Inspect(node, func(n ast.Node) bool {
		funcDecl, ok := n.(*ast.FuncDecl)
		if !ok || funcDecl.Recv == nil || len(funcDecl.Recv.List) == 0 {
			return true
		}
		if starExpr, ok := funcDecl.Recv.List[0].Type.(*ast.StarExpr); ok {
			if ident, ok := starExpr.X.(*ast.Ident); ok {
				structName := ident.Name
				if typeMethods[structName] == nil {
					typeMethods[structName] = make(map[string]*ast.FuncDecl)
				}
				typeMethods[structName][funcDecl.Name.Name] = funcDecl
			}
		}
		return true
	})

	// --- Step 2: Process fields and determine whether to use custom methods ---
	ast.Inspect(node, func(n ast.Node) bool {
		typeSpec, ok := n.(*ast.TypeSpec)
		if !ok {
			return true
		}
		structType, ok := typeSpec.Type.(*ast.StructType)
		if !ok {
			return true
		}

		structName := typeSpec.Name.Name
		if _, ok = g.structs[structName]; !ok {
			g.structs[structName] = &StructData{StructName: structName, Properties: []Property{}}
		}
		structData := g.structs[structName]
		methods := typeMethods[structName]

		for _, field := range structType.Fields.List {
			if field.Comment == nil || len(field.Names) == 0 {
				continue
			}
			commentText := field.Comment.List[0].Text
			if !strings.Contains(commentText, exporterPrefix) {
				continue
			}

			fieldName := field.Names[0].Name
			var typeNameBuf bytes.Buffer
			if err = printer.Fprint(&typeNameBuf, g.fileSet, field.Type); err != nil {
				log.Printf("warning: could not determine type for field %s: %v", fieldName, err)
				continue
			}
			fieldType := typeNameBuf.String()

			if !isTypeAllowed(fieldType) {
				log.Printf("warning: Skipping field '%s' with unsupported type '%s'", fieldName, fieldType)
				continue
			}

			goName := strings.ToUpper(fieldName[:1]) + fieldName[1:]
			doc := strings.TrimSpace(strings.Replace(commentText, exporterPrefix, "", -1))
			doc = strings.TrimPrefix(doc, "//")
			isReadOnly := strings.Contains(doc, readonlyKeyword)
			doc = strings.TrimSpace(strings.Replace(doc, readonlyKeyword, "", -1))
			if doc == "" {
				doc = goName
			}

			getterName, getterBody := "get"+goName, fmt.Sprintf("return s.ref.%s", fieldName)
			if getterFunc, found := g.getMethod(methods, goName, []string{"Get", "get"}); found {
				getterBody = fmt.Sprintf("return s.ref.%s()", getterFunc)
			}

			setterName, setterBody := "set"+goName, fmt.Sprintf("s.ref.%s = v\n\treturn nil", fieldName)
			if setterFunc, found := g.getMethod(methods, goName, []string{"Set", "set"}); found {
				setterDecl := methods[setterFunc]
				returnsError := false
				if setterDecl.Type.Results != nil && len(setterDecl.Type.Results.List) == 1 {
					if ident, ok := setterDecl.Type.Results.List[0].Type.(*ast.Ident); ok && ident.Name == "error" {
						returnsError = true
					}
				}
				if returnsError {
					setterBody = fmt.Sprintf("return s.ref.%s(v)", setterFunc)
				} else {
					setterBody = fmt.Sprintf("s.ref.%s(v)\n\treturn nil", setterFunc)
				}
			}

			structData.Properties = append(structData.Properties, Property{
				FieldName: fieldName, IDVarName: fieldName + "Id", GetterName: getterName, SetterName: setterName,
				FieldType: fieldType, Documentation: doc, ReadOnly: isReadOnly,
				GetterBody: getterBody, SetterBody: setterBody,
			})
		}
		return true
	})

	for _, data := range g.structs {
		if err = g.generateFile(data); err != nil {
			log.Printf("error generating file for struct %s: %v", data.StructName, err)
		}
	}

	return nil
}

// getMethod searches for a method name in the given map, combining a base name with provided prefixes.
// Returns the full method name and a boolean indicating if the method was found.
func (g *Generator) getMethod(methods map[string]*ast.FuncDecl, baseName string, prefixes []string) (string, bool) {
	for _, p := range prefixes {
		completeName := p + baseName
		if _, ok := methods[completeName]; ok {
			return completeName, true
		}
	}
	return "", false
}

// generateFile generates a Go source file based on the provided struct data and writes it to the configured output.
// If `useFile` is true, the output is written to a new file; otherwise, it writes to the provided `io.Writer`.
// Returns an error if template parsing or file operations fail.
func (g *Generator) generateFile(data *StructData) error {
	if len(data.Properties) == 0 {
		return nil
	}
	tmpl, err := template.New("reflect").Parse(reflectTemplate)
	if err != nil {
		return fmt.Errorf("error while creating template: %w", err)
	}

	writer := g.output
	if g.useFile {
		baseName := strings.ToLower(data.StructName)
		outputFilename := fmt.Sprintf("%s%s.go", baseName, exporterFileSuffix)
		outputFilepath := filepath.Join(filepath.Dir(g.inputFile), outputFilename)
		f, fErr := os.Create(outputFilepath)
		if fErr != nil {
			return fmt.Errorf("error while creating output file: %w", fErr)
		}
		defer f.Close()
		writer = f
	}

	templateData := TemplateData{
		PackageName: g.packageName,
		StructName:  data.StructName,
		Properties:  data.Properties,
	}
	return tmpl.Execute(writer, &templateData)
}
